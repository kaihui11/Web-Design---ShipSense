/* Lock the ISD input to the forecast data range and clamp its value */
function applyIsdBounds() {
  const isdEl = document.getElementById('input-isd');
  if (!isdEl || !FORECAST_DATA.length) return;
  const minDate = FORECAST_DATA[0].date;
  const maxDate = FORECAST_DATA[FORECAST_DATA.length - 1].date;
  isdEl.min = minDate;
  isdEl.max = maxDate;
  if (!isdEl.value || isdEl.value < minDate) isdEl.value = minDate;
  else if (isdEl.value > maxDate)            isdEl.value = maxDate;
}

/* ===== NEW FORECAST ===== */
function handleForecast() {
  const routeId       = document.getElementById('input-route')?.value || FIXED_ROUTE;
  const isdDate       = document.getElementById('input-isd').value;
  const containersRaw = document.getElementById('input-containers').value;
  const containers    = parseInt(containersRaw);
  const company       = document.getElementById('input-company').value.trim();
  const pic           = document.getElementById('input-pic').value.trim();

  if (!isdDate)                        { alert('Please select an Intended Ship Date.');     return; }
  if (!containersRaw || containers < 1) { alert('Please enter the number of containers.');   return; }
  if (!company)                        { alert('Please enter the Company Name.');           return; }
  if (!pic)                            { alert('Please enter the Person in Charge (PIC).'); return; }

  const minDate = FORECAST_DATA[0].date;
  const maxDate = FORECAST_DATA[FORECAST_DATA.length - 1].date;
  if (isdDate < minDate || isdDate > maxDate) {
    alert(`Intended Ship Date must be between ${fmtDate(minDate)} and ${fmtDate(maxDate)}.`);
    return;
  }

  const data = scaledData(routeId);

  /* Find closest available data point to ISD */
  let isdRow = data.find(d => d.date === isdDate);
  if (!isdRow) {
    isdRow = data.reduce((best, d) =>
      Math.abs(new Date(d.date) - new Date(isdDate)) <
      Math.abs(new Date(best.date) - new Date(isdDate)) ? d : best, data[0]);
  }

  /* ±5 day window */
  const isdIdx  = data.indexOf(isdRow);
  const wStart  = Math.max(0, isdIdx - 5);
  const wEnd    = Math.min(data.length - 1, isdIdx + 5);
  const dayWindow = data.slice(wStart, wEnd + 1);

  const lowestRow = dayWindow.reduce((mn, d) => d.f < mn.f ? d : mn, dayWindow[0]);

  state.currentForecast = {
    routeId, isdDate: isdRow.date, containers, company, pic,
    isdRow, lowestRow, dayWindow, allData: data,
    /* The date the client asked for. The lowest nearby date is shown
       alongside it as information the analyst can offer, but it is never
       applied automatically — the shipping date is the client's call. */
    clientDate: isdRow.date,
    pendingId: null, /* set when Client Quote page is first opened */
  };

  /* Feeds the Executive Dashboard's unified selectedISD (shared with its
     own "View Forecast for Date" picker) so a date chosen here shows up
     there automatically. */
  if (window.ExecData) ExecData.setSelectedISD(isdRow.date);

  /* The forecast figures come first. The user reviews the day grid and the
     lowest nearby fee here, then commits to a quote from this page via
     "Prepare Client Quote". */
  navigateTo('forecast-result');
}

