async function handleLogin(e) {
  e.preventDefault();
  const email = normalizeEmail(document.getElementById('login-email').value);
  const pw    = document.getElementById('login-password').value;
  const err   = document.getElementById('login-error');
  const btn   = document.getElementById('login-submit');

  if (!isAllowedEmail(email)) {
    err.textContent = `Please use your ${ALLOWED_EMAIL_DOMAIN} work email.`;
    err.classList.remove('hidden');
    return;
  }
  if (!pw) {
    err.textContent = 'Please enter your password.';
    err.classList.remove('hidden');
    return;
  }
  if (!sbClient) {
    err.textContent = 'Auth is not configured. Contact an administrator.';
    err.classList.remove('hidden');
    return;
  }
  err.classList.add('hidden');

  setBusy(btn, true, 'Signing in…', 'Login');
  const { data, error } = await sbClient.auth.signInWithPassword({ email, password: pw });
  setBusy(btn, false, 'Signing in…', 'Login');

  if (error) {
    err.textContent = error.message || 'Invalid email or password.';
    err.classList.remove('hidden');
    return;
  }

  await completeLogin(data.user);
}

