let HISTORY_DATA = [];

/* Maps a quote_requests row (snake_case, server-generated id) onto the
   camelCase shape the rest of this file already renders. */
function normalizeQuoteRow(r) {
  const created = new Date(r.created_at);
  return {
    id: r.id,
    ts: created.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) + '\n' +
        created.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' }),
    company: r.company, pic: r.pic, route: r.route,
    isdDate: r.isd_date, containers: r.containers, isdFee: r.isd_fee,
    lowDate: r.low_date, lowFee: r.low_fee, clientDate: r.client_date,
    status: r.status, decision: r.decision_date,
    /* Null until the quotation is issued — see issueQuotationFor(). */
    quoteRef: r.quote_ref, issuedAt: r.issued_at, validUntil: r.valid_until,
    quotedFee: r.quoted_fee == null ? null : Number(r.quoted_fee),
    quotedPrice: r.quoted_price == null ? null : Number(r.quoted_price),
    forecastGeneratedAt: r.forecast_generated_at,
  };
}

async function initHistory() {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/quote_requests?select=*&order=created_at.desc`, {
    headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const rows = await res.json();
  HISTORY_DATA = rows.map(normalizeQuoteRow);
}

/* Creates the Pending record in quote_requests and returns the
   normalized row, including its server-assigned id. */
async function insertHistoryRecord(entry) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/quote_requests`, {
    method: 'POST',
    headers: {
      apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      'Content-Type': 'application/json', Prefer: 'return=representation',
    },
    body: JSON.stringify({
      company: entry.company, pic: entry.pic, route: entry.route,
      isd_date: entry.isdDate, containers: entry.containers, isd_fee: entry.isdFee,
      low_date: entry.lowDate, low_fee: entry.lowFee, client_date: entry.clientDate,
      status: 'Pending',
    }),
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const [row] = await res.json();
  const normalized = normalizeQuoteRow(row);
  HISTORY_DATA.unshift(normalized);
  return normalized;
}

/* Patches an existing record (client_date/status/decision_date) in
   quote_requests and updates the in-memory cache. */
async function updateHistoryRecord(id, patch) {
  const body = {};
  if ('clientDate' in patch) body.client_date = patch.clientDate;
  if ('status'     in patch) body.status = patch.status;
  if ('decision'   in patch) body.decision_date = patch.decision;
  /* Editable request details — written by the Edit Record modal on the
     Forecast History page (see saveEditRecord()). The database refuses these
     on an issued quotation, which is why the modal only opens on rows that
     are still Pending and un-issued. */
  if ('company'    in patch) body.company = patch.company;
  if ('pic'        in patch) body.pic = patch.pic;
  if ('containers' in patch) body.containers = patch.containers;
  if ('isdDate'    in patch) body.isd_date = patch.isdDate;
  if ('isdFee'     in patch) body.isd_fee  = patch.isdFee;
  if ('lowDate'    in patch) body.low_date = patch.lowDate;
  if ('lowFee'     in patch) body.low_fee  = patch.lowFee;
  /* Issue fields — written once, by issueQuotationFor(). The database rejects
     any later attempt to change them (see schema.sql's lock trigger). */
  if ('quoteRef'    in patch) body.quote_ref    = patch.quoteRef;
  if ('issuedAt'    in patch) body.issued_at    = patch.issuedAt;
  if ('validUntil'  in patch) body.valid_until  = patch.validUntil;
  if ('quotedFee'   in patch) body.quoted_fee   = patch.quotedFee;
  if ('quotedPrice' in patch) body.quoted_price = patch.quotedPrice;
  if ('forecastGeneratedAt' in patch) body.forecast_generated_at = patch.forecastGeneratedAt;
  body.updated_at = new Date().toISOString();

  const res = await fetch(`${SUPABASE_URL}/rest/v1/quote_requests?id=eq.${id}`, {
    method: 'PATCH',
    headers: {
      apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      'Content-Type': 'application/json', Prefer: 'return=representation',
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const [row] = await res.json();
  const normalized = normalizeQuoteRow(row);
  const idx = HISTORY_DATA.findIndex(h => h.id === id);
  if (idx !== -1) HISTORY_DATA[idx] = normalized;
  return normalized;
}

/* Deletes a record outright — the D of the CRUD set, and the only operation
   here that destroys data rather than adding to it.

   The database is the authority on what may be deleted (schema.sql's
   "Delete pending requests" policy plus its delete guard); this function
   only carries the request. That split matters: an RLS policy that matches
   no row deletes nothing and still returns 200, so an empty response body
   means "the rules refused this row", not "done". Callers need to tell those
   apart, hence return=representation and the explicit check below. */
async function deleteHistoryRecord(id) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/quote_requests?id=eq.${id}`, {
    method: 'DELETE',
    headers: {
      apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      Prefer: 'return=representation',
    },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const rows = await res.json();
  if (!rows.length) {
    const err = new Error('Deletion was refused by the database rules.');
    err.blocked = true;
    throw err;
  }
  HISTORY_DATA = HISTORY_DATA.filter(h => String(h.id) !== String(id));
  return rows[0];
}

