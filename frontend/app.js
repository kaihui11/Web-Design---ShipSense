/* Emails are case-insensitive — normalize before validating/sending so
   "Name@GoodFortune.com" and "name@goodfortune.com" are treated (and
   stored) as the same address. */
function normalizeEmail(raw) {
  return raw.trim().toLowerCase();
}

/* Normalizes free-typed names to Title Case regardless of how the user
   typed it ("JOHN DOE" / "john doe" -> "John Doe"), including
   hyphenated/apostrophe'd names ("mary-jane o'brien" -> "Mary-Jane
   O'Brien"). */
function toTitleCase(raw) {
  return raw.trim().replace(/\s+/g, ' ')
    .toLowerCase()
    .replace(/[a-z]+/g, word => word.charAt(0).toUpperCase() + word.slice(1));
}

