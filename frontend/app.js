document.addEventListener('DOMContentLoaded', async () => {
  const submitBtn = document.querySelector('#login-form button[type="submit"]');
  const loginErr  = document.getElementById('login-error');
  submitBtn.disabled = true;
  submitBtn.textContent = 'Loading forecast data…';

  try {
    /* Two newest distinct runs: [0] is the latest, [1] the immediately
       previous one used for the revision comparison on the Forecast Result
       page. Each ingest appends a snapshot row, so id order is run order. */
    const index = await fetchSnapshotIndex();
    if (!index.length) throw new Error('no forecast data ingested yet');
    const runs = await fetchSnapshotRuns(index.slice(0, 2).map(r => r.id));
    if (!runs[0]?.forecast?.length) throw new Error('no forecast data ingested yet');

    FORECAST_DATA = runs[0].forecast;
    FORECAST_META = { generatedAt: runs[0].generatedAt };

    if (runs[1]) {
      PREV_FORECAST_DATA = runs[1].forecast;
      PREV_FORECAST_META = { generatedAt: runs[1].generatedAt };
    }
    submitBtn.disabled = false;
    submitBtn.textContent = 'Login';
  } catch (e) {
    console.error('Failed to load forecast data:', e);
    submitBtn.textContent = 'Data unavailable';
    loginErr.textContent  = 'Could not load forecast data from Supabase. Check SUPABASE_URL/SUPABASE_ANON_KEY and that a forecast snapshot has been ingested.';
    loginErr.classList.remove('hidden');
  }

  try {
    await initHistory();
  } catch (e) {
    console.error('Failed to load quote history:', e);
    HISTORY_DATA = [];
  }

  const today = new Date().toISOString().slice(0,10);
  const isdEl = document.getElementById('input-isd');
  if (isdEl) isdEl.value = today;
  applyIsdBounds();
  reInitLucide();

  /* Executive Dashboard's floating "Back to Top" button — shows once the
     page scrolls past 300px (the app scrolls at the window level, not
     inside .page-area). The button itself lives inside #page-executive,
     so it's already hidden on every other page/tab regardless of this
     listener still running while they're active. */
  const backToTopBtn = document.getElementById('exec-back-to-top');
  if (backToTopBtn) {
    window.addEventListener('scroll', () => {
      backToTopBtn.classList.toggle('visible', window.scrollY > 300);
    });
  }
});
