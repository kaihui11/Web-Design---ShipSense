/* Re-prices the working (not yet issued) quote as the date moves. Once a
   quotation exists, selectClientDate() routes to requoteForDate() instead —
   this guard is here so no other caller can quietly re-price an issued
   document. */
function updateClientQuote(selDate) {
  const cf = state.currentForecast;
  if (!cf) return;
  if (isIssued(currentQuoteRecord())) return;

  selDate = selDate || cf.clientDate || cf.isdDate;
  cf.clientDate = selDate;
  renderClientTotals(quoteFigures(cf, null));
}

/* ===== QUOTATION DOCUMENT (reference / issue / validity) =====
   The client-facing identity of the quote. Rendered on the preview and
   reproduced verbatim in the PDF so the two can never disagree. */
/* Carries only what the fields above it don't. The expiry is stated as a
   duration, not repeated as a date, because Valid Until sits directly above
   with the same timestamp. What's left is genuinely new: the shipping date
   being quoted (the client's choice, so it moves with the date picker) and
   the forecast run the price came from (fixed until a newer run lands). */
function validityStatement(f) {
  return `For shipment on ${fmtDate(f.clientDate)}, priced from market information of ` +
         `${fmtTs(f.forecastAt)} and held for ${QUOTE_VALIDITY_HOURS} hours from issue. ` +
         `Rates may be revised after that.`;
}

